/** Picks the right plural form of "event" — Polish needs one/few/many. */
export function pluralEvents(n, t) {
  const [one, few, many] = t.common.eventForms;
  const d = n % 10, h = n % 100;
  if (n === 1) return one;
  if (d >= 2 && d <= 4 && !(h >= 12 && h <= 14)) return few;
  return many;
}
